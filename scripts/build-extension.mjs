import { build } from "esbuild";
import { mkdir, writeFile, readFile } from "node:fs/promises";
// Self-contained MCP resource: no nested PWA, third-party cookies, remote JS,
// runtime network dependencies, or separate hosting account.
const result = await build({
  entryPoints: ["src/extension/main.jsx"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
});
const js = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const css = await readFile("src/extension/extension.css", "utf8");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>StreamLion</title><style>${css}</style></head><body><div id="root"></div><script>${js}</script></body></html>`;
await mkdir("server/generated", { recursive: true });
await writeFile(
  "server/generated/extension-ui.js",
  `// Generated by npm run build:extension; do not edit.\nexport const EXTENSION_HTML = ${JSON.stringify(html)};\n`,
);
await mkdir("dist", { recursive: true });
// Useful standalone fixture for the local host simulator; excluded from offline navigation.
await writeFile("dist/extension.html", html);
console.log("Built self-contained StreamLion MCP UI.");
